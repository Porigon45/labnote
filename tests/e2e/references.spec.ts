import { test, expect } from "@playwright/test";
import { entryFixture, fixture } from "./fixtures";

test("試料を登録・派生させ、プロトコルの使用版を固定し、研究メモを分類する", async ({ page, request }) => {
  const entry = entryFixture();
  const suffix = entry.id;
  await page.goto("/samples");
  await page.getByLabel("タイトル", { exact: true }).fill(`親株 ${suffix}`);
  await page.getByLabel("由来", { exact: true }).fill("保存株");
  await page.getByLabel("保管場所", { exact: true }).fill("冷凍庫A");
  await page.getByRole("button", { name: "作成する", exact: true }).click();
  await expect(page.getByRole("heading", { name: `親株 ${suffix}`, exact: true })).toBeVisible();
  const parentUrl = page.url();
  const parentId = parentUrl.split("/").pop()!;
  await page.goto("/samples");
  await page.getByLabel("タイトル", { exact: true }).fill(`派生株 ${suffix}`);
  await page.getByRole("combobox", { name: "親試料", exact: true }).selectOption(parentId);
  await page.getByRole("button", { name: "作成する", exact: true }).click();
  await expect(page.getByRole("heading", { name: `派生株 ${suffix}`, exact: true })).toBeVisible();
  const derivedId = page.url().split("/").pop()!;
  await page.getByRole("complementary", { name: "記録の情報" }).getByRole("link", { name: `親株 ${suffix}` }).click();
  await expect(page.getByRole("main").getByRole("link", { name: new RegExp(`派生株 ${suffix}`) })).toBeVisible();
  const protocol = fixture(repo => repo.create({ kind: "protocol", title: `測定手順 ${suffix}`, body: [{ id: "step1", type: "paragraph", content: [{ type: "text", text: "10分培養", styles: {} }] }] }));
  await page.goto(`/entries/${entry.id}`);
  await page.getByRole("combobox", { name: "参照先", exact: true }).selectOption(derivedId);
  await page.getByRole("button", { name: "参照を追加" }).click();
  await expect(page.getByRole("link", { name: `派生株 ${suffix} →`, exact: true })).toBeVisible();
  await page.getByRole("combobox", { name: "参照先", exact: true }).selectOption(protocol.id);
  await page.getByLabel("手順の変更点").fill("室温で実施");
  await page.getByRole("button", { name: "参照を追加" }).click();
  await expect(page.getByText(`${protocol.title} · 第1版（使用時の内容）`)).toBeVisible();
  const update = await request.patch(`/api/records/${protocol.id}`, { data: { revision: 1, body: [{ id: "step2", type: "paragraph", content: [{ type: "text", text: "20分培養", styles: {} }] }] } });
  expect(update.ok()).toBe(true);
  await page.reload();
  await page.getByText(`${protocol.title} · 第1版（使用時の内容）`).click();
  await expect(page.getByText("10分培養", { exact: true })).toBeVisible();
  await expect(page.getByText("20分培養", { exact: true })).toHaveCount(0);
  await expect(page.getByText("変更点: 室温で実施", { exact: true })).toBeVisible();
  await page.goto(`/samples/${derivedId}`);
  await expect(page.locator("section").filter({ has: page.getByRole("heading", { name: "使用した実験", exact: true }) }).getByRole("link", { name: /日次記録/ })).toBeVisible();
  await page.goto("/memos");
  await page.getByLabel("タイトル", { exact: true }).fill(`装置設定 ${suffix}`);
  await page.getByRole("combobox", { name: "カテゴリ", exact: true }).selectOption("装置・操作Tips");
  await page.getByRole("button", { name: "作成する", exact: true }).click();
  await expect(page.getByRole("heading", { name: `装置設定 ${suffix}`, exact: true })).toBeVisible();
  await page.goto(`/memos?category=${encodeURIComponent("装置・操作Tips")}`);
  await expect(page.getByRole("main").getByRole("link", { name: new RegExp(`装置設定 ${suffix}`) })).toBeVisible();
  await page.goto(`/memos?category=${encodeURIComponent("一般メモ")}`);
  await expect(page.getByText(`装置設定 ${suffix}`)).toHaveCount(0);
});
