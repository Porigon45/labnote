import { test, expect } from "@playwright/test";
import { entryFixture, fixture } from "./fixtures";
test("OD表を入力し、グラフを切り替えても値が変わらず、写真とキャプションを再表示できる", async ({ page, request }) => {
  const entry = entryFixture();
  await page.goto(`/entries/${entry.id}`);
  await page.getByLabel("追加するブロック").selectOption("measurement");
  await page.getByRole("button", { name: "追加", exact: true }).click();
  await page.getByLabel("A 値1", { exact: true }).fill("0.12");
  await page.getByLabel("B 値1", { exact: true }).fill("0.2");
  await page.getByRole("button", { name: "測定行を追加" }).click();
  await page.getByLabel("A 値2", { exact: true }).fill("0.4");
  await page.getByLabel("B 値2", { exact: true }).fill("0.5");
  await page.getByLabel("測定の表示").selectOption("line");
  await expect(page.getByLabel("測定グラフ")).toBeVisible();
  await page.getByLabel("測定の表示").selectOption("scatter");
  await page.getByLabel("測定の表示").selectOption("table");
  await expect(page.getByLabel("A 値1", { exact: true })).toHaveValue("0.12");
  await expect(page.getByLabel("本文の保存状態")).toHaveText("保存済み");
  expect(fixture(repo => repo.detail(entry.id).measurements[0].data.rows[1].values)).toEqual([0.4, 0.5]);
  const png = Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a9p0AAAAASUVORK5CYII=", "base64");
  await page.getByLabel("添付ファイル", { exact: true }).setInputFiles({ name: "result.png", mimeType: "image/png", buffer: png });
  await page.getByRole("button", { name: "アップロード", exact: true }).click();
  await expect(page.getByRole("link", { name: "result.png ↓" })).toBeVisible();
  await page.getByLabel("キャプション", { exact: true }).fill("培養結果の写真");
  await page.getByRole("button", { name: "キャプションを保存" }).click();
  await expect(page.getByLabel("添付の保存状態")).toContainText("キャプションを保存しました");
  await page.reload();
  await expect(page.getByRole("img", { name: "培養結果の写真" })).toBeVisible();
  await expect(page.getByLabel("A 値2", { exact: true })).toHaveValue("0.4");
  const unsupported = await request.post(`/api/records/${entry.id}/attachments?filename=bad.exe`, { data: "bad" });
  expect(unsupported.status()).toBe(415);
  await page.getByLabel("添付ファイル", { exact: true }).setInputFiles({ name: "note.txt", mimeType: "text/plain", buffer: Buffer.from("observation") });
  await page.route(`**/api/records/${entry.id}/attachments?*`, route => route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ error: "保存に失敗しました" }) }));
  await page.getByRole("button", { name: "アップロード", exact: true }).click();
  await expect(page.getByLabel("添付の保存状態")).toContainText("保存に失敗しました");
});
